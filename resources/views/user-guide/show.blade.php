<script>
document.addEventListener('DOMContentLoaded', function() {
    // Generate Table of Contents
    const content = document.querySelector('.guide-content');
    if (content) {
        const headings = content.querySelectorAll('h2, h3, h4');
        const toc = document.getElementById('toc');

        if (toc) {
            headings.forEach((heading, index) => {
                const id = `heading-${index}`;
                heading.id = id;

                const li = document.createElement('li');
                li.className = 'mb-1';

                const a = document.createElement('a');
                a.href = `#${id}`;
                a.textContent = heading.textContent;
                a.className = 'text-decoration-none text-secondary hover-primary small';

                if (heading.tagName === 'H3') {
                    a.style.marginLeft = '15px';
                }
                if (heading.tagName === 'H4') {
                    a.style.marginLeft = '30px';
                }

                li.appendChild(a);
                toc.appendChild(li);
            });
        }
    }
});

// Submit feedback
function submitFeedback(guideId, helpful) {
    const comment = document.getElementById('feedback-comment')?.value || '';

    fetch(`/user-guide/feedback/${guideId}`, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'X-CSRF-TOKEN': '{{ csrf_token() }}'
        },
        body: JSON.stringify({ helpful, comment })
    })
    .then(response => response.json())
    .then(data => {
        if (data.success) {
            alert(data.message);
            const percentageEl = document.getElementById('feedback-percentage');
            if (percentageEl) {
                percentageEl.textContent = data.helpful_percentage + '% found this helpful';
            }
        }
    })
    .catch(error => console.error('Error:', error));
}
</script>


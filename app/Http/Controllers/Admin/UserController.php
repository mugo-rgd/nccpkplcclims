    return view('admin.users.edit', compact('user', 'roles', 'userRoles'));
}

    /**
     * Update the specified user.
     */
     public function update(Request $request, User $user)
{
    $request->validate([
        'name' => ['required', 'string', 'max:255'],
        'email' => [
            'required',
            'string',
            'email',
            'max:255',
            Rule::unique('users', 'email')->ignore($user->id),
        ],

        'roles' => ['required', 'array', 'min:1'],
        'roles.*' => ['required', 'string', 'exists:roles,name'],

        'staff_number' => [
            'nullable',
            'string',
            'max:255',
            Rule::unique('users', 'staff_number')->ignore($user->id),
        ],
        'phone_number' => ['nullable', 'string', 'max:20'],
        'department' => ['nullable', 'string', 'max:255'],
        'designation' => ['nullable', 'string', 'max:100'],
        'station' => ['nullable', 'string', 'max:255'],
        'is_active' => ['nullable', 'boolean'],
        'status' => ['nullable', 'boolean'],
        'use_auto_signature' => ['nullable', 'boolean'],
        'password' => ['nullable', 'confirmed', Rules\Password::defaults()],
        'signature' => ['nullable', 'image', 'mimes:png,jpg,jpeg,gif', 'max:2048'],
    ]);

    try {
        $data = $request->except([
            'password',
            'password_confirmation',
            'signature',
            'roles',
        ]);

        if ($request->filled('password')) {
            $data['password'] = Hash::make($request->password);
        }

        $data['is_active'] = $request->has('is_active');
        $data['status'] = $request->has('status');
        $data['use_auto_signature'] = $request->has('use_auto_signature');

        if ($request->hasFile('signature')) {
            $file = $request->file('signature');

            $filename = time() . '_' . str_replace(' ', '_', strtolower($request->name)) . '_signature.' . $file->getClientOriginalExtension();

            $path = $file->storeAs('signatures', $filename, 'public');

            $data['signature_path'] = $path;
            $data['signature_filename'] = $filename;
            $data['signature_updated_at'] = now();
        }

        $user->update($data);

        $user->syncRoles($request->roles);

        return redirect()
            ->route('admin.users.index')
            ->with('success', 'User updated successfully with selected roles.');

    } catch (\Exception $e) {
        Log::error('Failed to update user: ' . $e->getMessage());

        return back()
            ->with('error', 'Failed to update user: ' . $e->getMessage())
            ->withInput();
    }
}

    /**
     * Update the user's password.
     */
    public function updatePassword(Request $request, User $user)
    {
        $request->validate([
            'password' => ['required', 'confirmed', Rules\Password::defaults()],
        ]);

        $user->update([
            'password' => Hash::make($request->password),
        ]);

        return redirect()
            ->route('users.show', $user)
            ->with('success', 'Password updated successfully!');
    }

    /**
     * Remove the specified user.
     */
    public function destroy(User $user)
    {
        // Prevent deleting yourself
        if (auth()->id() === $user->id) {
            return redirect()
                ->route('users.index')
                ->with('error', 'You cannot delete your own account.');
        }

        // Prevent deleting the last super_admin
        if ($user->hasRole('super_admin') && User::role('super_admin')->count() <= 1) {
            return redirect()
                ->route('users.index')
                ->with('error', 'Cannot delete the last super administrator.');
        }

        $user->delete();

        return redirect()
            ->route('users.index')
            ->with('success', 'User deleted successfully!');
    }


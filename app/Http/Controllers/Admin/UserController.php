   public function create()
{
    $roles = Role::orderBy('name')->get();

    return view('admin.users.create', compact('roles'));
}
    /**
     * Store a newly created user.
     */
   public function store(Request $request)
{
    $request->validate([
        'name' => ['required', 'string', 'max:255'],
        'email' => ['required', 'string', 'email', 'max:255', 'unique:users,email'],
        'password' => ['required', 'confirmed', Rules\Password::defaults()],

        'roles' => ['required', 'array', 'min:1'],
        'roles.*' => ['required', 'string', 'exists:roles,name'],

        'staff_number' => ['nullable', 'string', 'max:255', 'unique:users,staff_number'],
        'phone_number' => ['nullable', 'string', 'max:20'],
        'department' => ['nullable', 'string', 'max:255'],
        'designation' => ['nullable', 'string', 'max:100'],
        'station' => ['nullable', 'string', 'max:255'],
        'is_active' => ['nullable', 'boolean'],
        'status' => ['nullable', 'boolean'],
        'use_auto_signature' => ['nullable', 'boolean'],
        'signature' => ['nullable', 'image', 'mimes:png,jpg,jpeg,gif', 'max:2048'],
    ]);

    try {
        $data = $request->except([
            'password',
            'password_confirmation',
            'signature',
            'roles',
        ]);

        $data['password'] = Hash::make($request->password);
        $data['is_active'] = $request->has('is_active');
        $data['status'] = $request->has('status');
        $data['use_auto_signature'] = $request->has('use_auto_signature');

        if ($request->hasFile('signature')) {
            $file = $request->file('signature');

            $filename = time() . '_' . str_replace(' ', '_', strtolower($request->name)) . '_signature.' . $file->getClientOriginalExtension();

            $path = $file->storeAs('signatures', $filename, 'public');

            $data['signature_path'] = $path;
            $data['signature_filename'] = $filename;
            $data['signature_updated_at'] = now();
        }

        $user = User::create($data);

        $user->assignRole($request->roles);

        return redirect()
            ->route('admin.users.index')
            ->with('success', 'User created successfully with selected roles.');

    } catch (\Exception $e) {
        Log::error('Failed to create user: ' . $e->getMessage());

        return back()
            ->with('error', 'Failed to create user: ' . $e->getMessage())
            ->withInput();
    }
}

   /**
 * Display the specified user.
 */
public function show(User $user)
{
    /*
    |--------------------------------------------------------------------------
    | Load basic user relationships
    |--------------------------------------------------------------------------
    */

    $user->load([
        'roles',
    ]);

    /*
    |--------------------------------------------------------------------------
    | Calibrations performed by this user
    |--------------------------------------------------------------------------
    */

    $calibrations = \App\Models\Calibration::query()
        ->with([
            'customer',
            'equipmentType',
        ])
        ->where(
            'performed_by',
            $user->id
        )
        ->latest('created_at')
        ->paginate(
            15,
            ['*'],
            'calibrations_page'
        );

    /*
    |--------------------------------------------------------------------------
    | Certificates generated by this user
    |--------------------------------------------------------------------------
    */

    $certificates = \App\Models\Certificate::query()
        ->with([
            'calibration',
            'customer',
        ])
        ->where(
            'generated_by',
            $user->id
        )
        ->latest('created_at')
        ->paginate(
            15,
            ['*'],
            'certificates_page'
        );

    /*
    |--------------------------------------------------------------------------
    | Recent user activity
    |--------------------------------------------------------------------------
    */

    $activities = \App\Models\ActivityLog::query()
        ->where(
            'user_id',
            $user->id
        )
        ->latest('created_at')
        ->limit(10)
        ->get();

    /*
    |--------------------------------------------------------------------------
    | Summary statistics
    |--------------------------------------------------------------------------
    */

    $stats = [
        'calibrations_count' =>
            \App\Models\Calibration::query()
                ->where(
                    'performed_by',
                    $user->id
                )
                ->count(),

        'certificates_generated_count' =>
            \App\Models\Certificate::query()
                ->where(
                    'generated_by',
                    $user->id
                )
                ->count(),

        'certificates_checked_count' =>
            \App\Models\Certificate::query()
                ->where(
                    'checked_by',
                    $user->id
                )
                ->count(),

        'certificates_approved_count' =>
            \App\Models\Certificate::query()
                ->where(
                    'approved_by',
                    $user->id
                )
                ->count(),

        'certificates_issued_count' =>
            \App\Models\Certificate::query()
                ->where(
                    'issued_by',
                    $user->id
                )
                ->count(),

        'certificates_sent_count' =>
            \App\Models\Certificate::query()
                ->where(
                    'sent_by',
                    $user->id
                )
                ->count(),
    ];

    return view(
        'admin.users.show',
        [
            'user' => $user,
            'calibrations' => $calibrations,
            'certificates' => $certificates,
            'activities' => $activities,
            'stats' => $stats,
        ]
    );
}


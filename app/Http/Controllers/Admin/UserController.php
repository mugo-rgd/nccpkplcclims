    /**
 * Upload user signature
 */
public function uploadSignature(Request $request, User $user)
{
    $request->validate([
        'signature' => 'required|image|mimes:png,jpg,jpeg|max:2048',
    ]);

    $path = $request->file('signature')->store('signatures', 'public');

    $user->update([
        'signature_path' => $path,
        'signature_filename' => $request->file('signature')->getClientOriginalName(),
        'use_auto_signature' => true,
        'signature_updated_at' => now(),
    ]);

    return back()->with('success', 'Signature uploaded successfully!');
}

/**
 * Toggle user active status
 */
public function toggleStatus(User $user)
{
    try {
        // Prevent toggling your own status
        if ($user->id === auth()->id()) {
            return redirect()->route('admin.users.index')
                ->with('error', 'You cannot change your own status.');
        }

        // Toggle the status
        $user->is_active = !$user->is_active;
        $user->save();

        $status = $user->is_active ? 'activated' : 'deactivated';

        Log::info('User status toggled', [
            'user_id' => $user->id,
            'name' => $user->name,
            'new_status' => $user->is_active ? 'active' : 'inactive',
            'performed_by' => auth()->id()
        ]);

        return redirect()->route('admin.users.index')
            ->with('success', "User {$user->name} has been {$status} successfully!");

    } catch (\Exception $e) {
        Log::error('Failed to toggle user status: ' . $e->getMessage(), [
            'user_id' => $user->id
        ]);

        return redirect()->route('admin.users.index')
            ->with('error', 'Failed to toggle user status: ' . $e->getMessage());
    }
}

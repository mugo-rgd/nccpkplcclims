<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use App\Models\QualityObjective;
use App\Models\QuarterlyAchievement;
use App\Models\QualityFyrPeriod;
use App\Models\User;
use Carbon\Carbon;

class CreateTestAchievements extends Command
{
    protected $signature = 'quality:test-data';
    protected $description = 'Create test achievement data for demonstration';

    public function handle()
    {
        $this->info('🔄 Creating test achievement data...');

        $currentFyr = QualityFyrPeriod::getCurrentFYR();
        if (!$currentFyr) {
            $this->error('No current FYR found.');
            return 1;
        }

        $user = User::first();
        if (!$user) {
            $this->error('No user found.');
            return 1;
        }

        $objectives = QualityObjective::where('target_fyr', $currentFyr->fyr)->get();
        $quarters = ['Q1', 'Q2', 'Q3'];

        $bar = $this->output->createProgressBar(count($objectives) * count($quarters));

        foreach ($objectives as $objective) {
            foreach ($quarters as $quarterIndex => $quarter) {
                // Generate random achievement between 80-105% of target
                $percentage = rand(80, 105);
                $achievement = ($percentage / 100) * $objective->target_value;

                // For 'Days' objectives, achievement should be lower than target (better performance)
                if (in_array($objective->unit_of_measure, ['Days', 'Hours'])) {
                    $achievement = $objective->target_value - (rand(0, 10) / 10);
                    if ($achievement < 0.1) $achievement = 0.1;
                }

                $quarterLabel = 'Sept 2023';
                if ($quarterIndex == 1) $quarterLabel = 'Dec 2023';
                if ($quarterIndex == 2) $quarterLabel = 'Mar 2024';

                QuarterlyAchievement::create([
                    'objective_id' => $objective->id,
                    'fyr_period_id' => $currentFyr->id,
                    'quarter' => $quarter,
                    'quarter_label' => $quarterLabel,
                    'actual_achievement' => round($achievement, 2),
                    'data_collection_date' => Carbon::now()->subMonths(3 - $quarterIndex),
                    'collected_by_id' => $user->id,
                    'remarks' => 'Test data generated by command'
                ]);

                $bar->advance();
            }
        }

        $bar->finish();
        $this->newLine();
        $this->info('✅ Test data created successfully!');

        return 0;
    }
}
